  var RE_CJK = /[\u3400-\u9fff\uf900-\ufaff]/;
  var sorted = null;
  var lang = 'en';

  function prepare() {
    sorted = PAIRS.slice().sort(function (a, b) { return b[0].length - a[0].length; });
  }

  /* T(s)：把一段中文文案翻成英文；lang=zh 时原样返回（中文就是原文）。 */
  function T(s) {
    if (lang !== 'en' || typeof s !== 'string' || !RE_CJK.test(s)) return s;
    if (!sorted) prepare();
    var out = s;
    for (var i = 0; i < sorted.length; i++) {
      var zh = sorted[i][0];
      if (out.indexOf(zh) >= 0) out = out.split(zh).join(sorted[i][1]);
    }
    return out;
  }

  function setLang(l) { lang = l === 'zh' ? 'zh' : 'en'; }
  function getLang() { return lang; }

  /* localizeDOM：把 index.html 里的静态文案（文本节点 + placeholder/title/aria-label）
   * 按 T() 换一遍；原始中文记在 WeakMap 里，切回中文时能还原。 */
  var originals = new WeakMap();
  var SKIP = { SCRIPT: 1, STYLE: 1, TEXTAREA: 1 };
  var ATTRS = ['placeholder', 'title', 'aria-label'];

  function localizeNode(node) {
    if (node.nodeType === 3) {
      var parent = node.parentNode;
      if (!parent || SKIP[parent.nodeName]) return;
      if (!originals.has(node)) originals.set(node, node.nodeValue);
      var orig = originals.get(node);
      var next = T(orig);
      if (node.nodeValue !== next) node.nodeValue = next;
      return;
    }
    if (node.nodeType !== 1) return;
    for (var i = 0; i < ATTRS.length; i++) {
      var a = ATTRS[i];
      if (!node.hasAttribute(a)) continue;
      var key = '@' + a;
      var store = originals.get(node) || {};
      if (!(key in store)) store[key] = node.getAttribute(a);
      originals.set(node, store);
      var v = T(store[key]);
      if (node.getAttribute(a) !== v) node.setAttribute(a, v);
    }
    for (var c = node.firstChild; c; c = c.nextSibling) localizeNode(c);
  }

  function localizeDOM(root) {
    localizeNode(root || document.body);
  }

  global.MPI = { T: T, setLang: setLang, getLang: getLang, localizeDOM: localizeDOM };
